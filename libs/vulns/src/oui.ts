export interface VendorInfo {
  vendor: string;
  type?: DeviceType;
}

export function lookupVendor(mac: string): VendorInfo | null {
  if (!mac) return null;
  const normalized = mac
    .replace(/[.:-]/g, ":")
    .toUpperCase();

  const segments = normalized.split(":").filter(Boolean);
  if (segments.length < 3) return null;

  const prefix3 = `${segments[0]}:${segments[1]}:${segments[2]}`;
  const prefix2 = `${segments[0]}:${segments[1]}`;

  const exact = OUI_TABLE.find((e) => e.prefix === prefix3) ||
    OUI_TABLE.find((e) => e.prefix === prefix2);
  if (!exact) return null;

  return { vendor: exact.vendor, type: exact.type };
}